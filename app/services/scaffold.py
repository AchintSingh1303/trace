"""Turn approved API test cases into a pytest skeleton.

This saves the typing and keeps the link from each test back to its requirement. It does not write assertions:
the expected results are copied in as comments for a person to turn into checks.
"""

from __future__ import annotations

import json
import re

from sqlalchemy import select
from sqlalchemy.orm import Session, selectinload

from ..models import Requirement, TestCase

HEADER = '''"""pytest scaffold generated by TRACE for cycle {cycle_id}.

This is a starting point, not a finished suite. Each test sends the request the case describes and leaves the
assertions as TODO comments built from the expected results. Fill them in, then run:

    TRACE_TARGET_URL=http://localhost:8000 pytest

Tests carry a requirement marker so you can run one requirement at a time:  pytest -m "requirement('RQ-005')"
Register it in pytest.ini to silence the warning:  markers = requirement(code): the requirement a test covers
"""

import os

import pytest
import requests

BASE_URL = os.environ.get("TRACE_TARGET_URL", "http://localhost:8000").rstrip("/")
TIMEOUT = 10
'''


def _line(text: str) -> str:
    """Make arbitrary text safe to put after '# ' on one line."""
    return " ".join((text or "").split())


def _func_name(tc_code: str) -> str:
    return "test_" + re.sub(r"[^a-z0-9]+", "_", tc_code.lower()).strip("_")


def _data(tc: TestCase, name: str) -> str:
    for item in tc.test_data:
        if item.field_name == name and item.value:
            return item.value
    return ""


def build_pytest(db: Session, cycle_id: int) -> tuple[str, dict]:
    cases = db.scalars(
        select(TestCase)
        .where(TestCase.cycle_id == cycle_id, TestCase.status == "approved", TestCase.test_type == "api")
        .order_by(TestCase.tc_code)
        .options(selectinload(TestCase.steps), selectinload(TestCase.test_data), selectinload(TestCase.links))
    ).all()
    reqs = {r.id: r.code for r in db.scalars(select(Requirement).where(Requirement.cycle_id == cycle_id))}

    out = [HEADER.format(cycle_id=cycle_id)]
    skipped = []
    written = 0
    for tc in cases:
        method = _data(tc, "method").upper()
        path = _data(tc, "endpoint")
        if not method or not path:
            skipped.append(tc.tc_code)
            continue
        written += 1
        codes = sorted({reqs[l.requirement_id] for l in tc.links if l.requirement_id in reqs})
        out.append("")
        out.append("")
        for code in codes:
            out.append(f"@pytest.mark.requirement({json.dumps(code)})")
        out.append(f"def {_func_name(tc.tc_code)}():")
        out.append(f"    # {tc.tc_code} ({tc.priority}): {_line(tc.title)}")
        if "{" in path:
            out.append("    # The path has a placeholder. Replace it with a real id before running.")
        for step in tc.steps:
            out.append(f"    # Step {step.seq}: {_line(step.action)}")
            if step.expected:
                out.append(f"    #   Expected: {_line(step.expected)}")
        out.append(f"    response = requests.request({json.dumps(method)}, BASE_URL + {json.dumps(path)}, timeout=TIMEOUT)")
        out.append("    # TODO: replace with assertions built from the expected results above")
        out.append("    assert response is not None")

    if skipped:
        out.append("")
        out.append("")
        out.append("# Not written, because the case has no method or endpoint in its test data:")
        out.extend(f"#   {code}" for code in skipped)
    return "\n".join(out) + "\n", {"written": written, "skipped": skipped, "approved_api_cases": len(cases)}
